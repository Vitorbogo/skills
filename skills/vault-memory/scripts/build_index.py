#!/usr/bin/env python3
"""Build INDEX.md for a markdown vault: one line per note, from its frontmatter.

Usage:
  build_index.py [VAULT]         write INDEX.md and print a summary
  build_index.py --hook [VAULT]  write INDEX.md and print it for a SessionStart hook

VAULT defaults to $VAULT_PATH. In hook mode an unset or missing vault prints nothing.
"""
import os
import sys

INDEX = "INDEX.md"
SKIP_DIRS = {".obsidian", ".git", ".trash", "node_modules"}
# Past this size the hook injects a pointer instead of the whole index, so a big
# vault does not spend thousands of tokens on every session.
HOOK_MAX_CHARS = int(os.environ.get("VAULT_INDEX_MAX_CHARS", "9000"))


def frontmatter(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "\t", "-")):
            meta[key.strip()] = value.strip().strip("\"'")
    return meta


def notes(vault):
    for root, dirs, files in os.walk(vault):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(files):
            rel = os.path.relpath(os.path.join(root, name), vault)
            if name.endswith(".md") and rel != INDEX:
                yield rel, frontmatter(os.path.join(root, name))


def build(vault):
    sections, missing, total = {}, [], 0
    for rel, meta in notes(vault):
        total += 1
        desc = meta.get("description", "")
        if not desc:
            missing.append(rel)
        extra = ", ".join(v for v in (meta.get("type", ""), meta.get("tags", "").strip("[]")) if v)
        line = f"- `{rel}` — {desc or '(no description)'}" + (f" _({extra})_" if extra else "")
        top = rel.split(os.sep)[0] if os.sep in rel else "(root)"
        sections.setdefault(top, []).append(line)

    out = [
        "# Index",
        "",
        "Generated by build_index.py from each note's frontmatter. Do not edit by hand.",
        f"{total} notes, {len(missing)} without a description.",
    ]
    for top in sorted(sections):
        out += ["", f"## {top}", "", *sections[top]]
    if missing:
        out += ["", "## Missing description", "", *(f"- `{m}`" for m in missing)]
    text = "\n".join(out) + "\n"
    path = os.path.join(vault, INDEX)
    # Rewrite only on change, so a synced or git-tracked vault sees no churn.
    if not os.path.isfile(path) or open(path, encoding="utf-8").read() != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    return text, total, len(missing)


def main():
    args = sys.argv[1:]
    hook = "--hook" in args
    args = [a for a in args if a != "--hook"]
    vault = os.path.expanduser(args[0] if args else os.environ.get("VAULT_PATH", ""))
    if not vault or not os.path.isdir(vault):
        if hook:
            return
        sys.exit(f"vault not found: {vault or '$VAULT_PATH is unset'}")

    text, total, missing = build(vault)
    index_path = os.path.join(vault, INDEX)
    if not hook:
        print(f"wrote {index_path}: {total} notes, {missing} without a description")
    elif len(text) <= HOOK_MAX_CHARS:
        print(f"Knowledge vault at {vault}. Use the vault skill before reading or writing it.\n\n{text}")
    else:
        print(f"Knowledge vault at {vault} ({total} notes). Use the vault skill, and read {index_path} before a task that touches it.")


if __name__ == "__main__":
    main()
